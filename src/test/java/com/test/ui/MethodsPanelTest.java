package com.test.ui;

import com.study.parser.ParseResult;
import com.study.ui.panel.MethodsPanel;
import org.junit.Test;

import javax.swing.JLabel;
import javax.swing.JTable;
import javax.swing.JTextArea;
import java.util.List;
import java.util.Optional;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertFalse;
import static org.junit.Assert.assertTrue;

/**
 * Verifies the methods table (one row per method, names and descriptors), the
 * detail pane filled with the presenter output (identical to the CLI), and
 * the embedded JVMS Table 4.6-A mirroring the selected method's access flags.
 */
public class MethodsPanelTest {

    private static final String CASE = "com/test/ui/cases/GuiShowcaseCase.class";

    @Test
    public void listsEveryMethodWithItsDescriptor() {
        ParseResult result = GuiTestSupport.parse(CASE);
        GuiTestSupport.onEdt(() -> {
            MethodsPanel panel = new MethodsPanel(result);
            JTable table = GuiTestSupport.findComponent(panel, JTable.class);

            assertEquals(result.getMethods().getCount(), table.getRowCount());
            assertEquals("access flags", table.getColumnName(0));
            assertEquals("name", table.getColumnName(1));
            assertEquals("descriptor", table.getColumnName(2));
            assertEquals("attributes", table.getColumnName(3));

            JLabel countLabel = GuiTestSupport.findComponent(panel, JLabel.class);
            assertEquals(" Methods: " + result.getMethods().getCount(), countLabel.getText());

            assertTrue(GuiTestSupport.findRow(table, 1, "<init>") >= 0);

            int interfaceCallRow = GuiTestSupport.findRow(table, 1, "interfaceCall");
            assertTrue(interfaceCallRow >= 0);
            assertEquals("(Ljava/util/List;)I", table.getValueAt(interfaceCallRow, 2));

            int concatRow = GuiTestSupport.findRow(table, 1, "stringConcat");
            assertTrue(concatRow >= 0);
            assertEquals("(Ljava/lang/String;)Ljava/lang/String;", table.getValueAt(concatRow, 2));
        });
    }

    @Test
    public void selectingARowShowsThePresenterOutput() {
        ParseResult result = GuiTestSupport.parse(CASE);
        GuiTestSupport.onEdt(() -> {
            MethodsPanel panel = new MethodsPanel(result);
            JTable table = GuiTestSupport.findComponent(panel, JTable.class);
            JTextArea detail = GuiTestSupport.findComponent(panel, JTextArea.class);

            // the first row is pre-selected, so the detail pane is already filled
            assertFalse(detail.getText().isBlank());

            int virtualCallRow = GuiTestSupport.findRow(table, 1, "virtualCall");
            table.setRowSelectionInterval(virtualCallRow, virtualCallRow);
            assertTrue(detail.getText().contains("descriptor: ()Ljava/lang/String;"));
            assertTrue(detail.getText().contains("Code:"));

            int lambdaRow = GuiTestSupport.findRow(table, 1, "lambda");
            table.setRowSelectionInterval(lambdaRow, lambdaRow);
            assertTrue(detail.getText().contains("descriptor: ()Ljava/lang/Runnable;"));
            assertTrue(detail.getText().contains("Code:"));
        });
    }

    @Test
    public void accessFlagsTableMirrorsSelectedMethod() {
        ParseResult result = GuiTestSupport.parse(CASE);
        GuiTestSupport.onEdt(() -> {
            MethodsPanel panel = new MethodsPanel(result);
            JTable table = GuiTestSupport.findComponent(panel, JTable.class);
            JTable flags = flagsTable(panel);

            // JVMS Table 4.6-A: twelve flags, four columns
            assertEquals(12, flags.getRowCount());
            assertEquals(4, flags.getColumnCount());
            assertEquals("Flag name", flags.getColumnName(0));
            assertEquals("Value", flags.getColumnName(1));
            assertEquals("Set", flags.getColumnName(2));
            assertEquals("Interpretation", flags.getColumnName(3));

            // exact spec wording (SE 27 Table 4.6-A)
            int finalRow = GuiTestSupport.findRow(flags, 0, "ACC_FINAL");
            assertEquals("Declared final; must not be overridden (§5.4.5).", flags.getValueAt(finalRow, 3));
            int bridgeRow = GuiTestSupport.findRow(flags, 0, "ACC_BRIDGE");
            assertEquals("A bridge method, generated by the compiler.", flags.getValueAt(bridgeRow, 3));
            int strictRow = GuiTestSupport.findRow(flags, 0, "ACC_STRICT");
            assertEquals("In a class file whose major version number is at least 46 and at most 60: "
                            + "Declared strictfp.",
                    flags.getValueAt(strictRow, 3));

            // initial selection is row 0 (<init>): public only
            assertSetFlags(flags, "ACC_PUBLIC");
            assertUnsetFlags(flags, "ACC_PRIVATE", "ACC_STATIC", "ACC_SYNTHETIC");

            // selecting the compiler-generated lambda method flips to private static synthetic
            int syntheticRow = -1;
            for (int row = 0; row < table.getRowCount(); row++) {
                if (String.valueOf(table.getValueAt(row, 0)).contains("ACC_SYNTHETIC")) {
                    syntheticRow = row;
                    break;
                }
            }
            assertTrue("no synthetic method row in the fixture", syntheticRow >= 0);
            table.setRowSelectionInterval(syntheticRow, syntheticRow);
            // javac generates an instance method for a lambda capturing only `this`
            assertSetFlags(flags, "ACC_PRIVATE", "ACC_SYNTHETIC");
            assertUnsetFlags(flags, "ACC_PUBLIC", "ACC_STATIC", "ACC_BRIDGE", "ACC_VARARGS");
        });
    }

    private static JTable flagsTable(MethodsPanel panel) {
        List<JTable> tables = GuiTestSupport.findAll(panel, JTable.class);
        Optional<JTable> flags = tables.stream()
                .filter(table -> table.getColumnCount() == 4 && "Flag name".equals(table.getColumnName(0)))
                .findFirst();
        assertTrue("access flags table not found among " + tables.size() + " tables", flags.isPresent());
        return flags.get();
    }

    private static void assertSetFlags(JTable flags, String... names) {
        for (String name : names) {
            int row = GuiTestSupport.findRow(flags, 0, name);
            assertTrue("row not found: " + name, row >= 0);
            assertEquals("Set column for " + name, "✓", flags.getValueAt(row, 2));
        }
    }

    private static void assertUnsetFlags(JTable flags, String... names) {
        for (String name : names) {
            int row = GuiTestSupport.findRow(flags, 0, name);
            assertTrue("row not found: " + name, row >= 0);
            assertEquals("Set column for " + name, "", flags.getValueAt(row, 2));
        }
    }
}
