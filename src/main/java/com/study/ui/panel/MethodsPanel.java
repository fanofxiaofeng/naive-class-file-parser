package com.study.ui.panel;

import com.study.constants.MethodAccessFlags;
import com.study.parser.ParseResult;
import com.study.present.MethodInfoPresenter;
import com.study.type.ConstantPool;
import com.study.type.info.MethodInfo;
import com.study.ui.support.AccessFlagsTable;
import com.study.ui.support.TextCapture;
import com.study.ui.support.TextAreas;

import javax.swing.BorderFactory;
import javax.swing.JLabel;
import javax.swing.JPanel;
import javax.swing.JScrollPane;
import javax.swing.JSplitPane;
import javax.swing.JTable;
import javax.swing.JTextArea;
import javax.swing.ListSelectionModel;
import javax.swing.table.AbstractTableModel;
import java.awt.BorderLayout;
import java.util.Arrays;
import java.util.EnumMap;
import java.util.List;
import java.util.Map;

/**
 * Method table plus a detail pane. The detail pane reuses
 * {@link MethodInfoPresenter}, which renders the header line (with the
 * human-readable signature), descriptor, flags and all attributes
 * (including Code: instructions, exception table, line number table, ...).
 * The selected method's access flags are rendered as the embedded JVMS
 * Table 4.6-A, with the set rows highlighted.
 */
public class MethodsPanel extends JPanel {

    /**
     * JVMS §4.6 Table 4.6-A: method access and property modifiers.
     */
    private static final Map<MethodAccessFlags, String> FLAG_MEANINGS = new EnumMap<>(Map.ofEntries(
            Map.entry(MethodAccessFlags.ACC_PUBLIC,
                    "Declared public; may be accessed from outside its package."),
            Map.entry(MethodAccessFlags.ACC_PRIVATE,
                    "Declared private; accessible only within the defining class "
                            + "and other classes belonging to the same nest (§5.4.4)."),
            Map.entry(MethodAccessFlags.ACC_PROTECTED,
                    "Declared protected; may be accessed within subclasses."),
            Map.entry(MethodAccessFlags.ACC_STATIC,
                    "Declared static."),
            Map.entry(MethodAccessFlags.ACC_FINAL,
                    "Declared final; must not be overridden (§5.4.5)."),
            Map.entry(MethodAccessFlags.ACC_SYNCHRONIZED,
                    "Declared synchronized; invocation is wrapped by a monitor use."),
            Map.entry(MethodAccessFlags.ACC_BRIDGE,
                    "A bridge method, generated by the compiler."),
            Map.entry(MethodAccessFlags.ACC_VARARGS,
                    "Declared with variable number of arguments."),
            Map.entry(MethodAccessFlags.ACC_NATIVE,
                    "Declared native; implemented in a language other than the Java programming language."),
            Map.entry(MethodAccessFlags.ACC_ABSTRACT,
                    "Declared abstract; no implementation is provided."),
            Map.entry(MethodAccessFlags.ACC_STRICT,
                    "In a class file whose major version number is at least 46 and at most 60: "
                            + "Declared strictfp."),
            Map.entry(MethodAccessFlags.ACC_SYNTHETIC,
                    "Declared synthetic; not present in the source code.")
    ));

    private static final List<AccessFlagsTable.FlagRow> FLAG_ROWS = Arrays.stream(MethodAccessFlags.values())
            .map(flag -> new AccessFlagsTable.FlagRow(flag.name(), flag.getFlag(), FLAG_MEANINGS.get(flag)))
            .toList();

    private final ParseResult result;
    private final JTextArea detailArea = TextAreas.readOnlyMonospace();
    private final AccessFlagsTable flagsTable;

    public MethodsPanel(ParseResult result) {
        super(new BorderLayout());
        this.result = result;

        List<MethodInfo> methods = result.getMethods().items();
        JTable table = new JTable(new MethodsTableModel(result.getConstantPool(), methods));
        table.setSelectionMode(ListSelectionModel.SINGLE_SELECTION);
        table.getColumnModel().getColumn(0).setPreferredWidth(180);
        table.getColumnModel().getColumn(1).setPreferredWidth(180);
        table.getColumnModel().getColumn(2).setPreferredWidth(380);
        table.getColumnModel().getColumn(3).setPreferredWidth(70);

        this.flagsTable = new AccessFlagsTable(FLAG_ROWS,
                methods.isEmpty() ? 0 : methods.get(0).getAccessFlags().toInt());
        JScrollPane flagsPane = new JScrollPane(flagsTable);
        flagsPane.setBorder(BorderFactory.createTitledBorder("access_flags (JVMS Table 4.6-A)"));

        table.getSelectionModel().addListSelectionListener(event -> {
            if (event.getValueIsAdjusting()) {
                return;
            }
            int selected = table.getSelectedRow();
            if (selected >= 0) {
                showDetail(methods.get(table.convertRowIndexToModel(selected)));
            }
        });

        JSplitPane detailSplit = new JSplitPane(JSplitPane.VERTICAL_SPLIT,
                flagsPane, new JScrollPane(detailArea));
        detailSplit.setResizeWeight(0.45);
        detailSplit.setContinuousLayout(true);

        JSplitPane splitPane = new JSplitPane(JSplitPane.VERTICAL_SPLIT,
                new JScrollPane(table), detailSplit);
        splitPane.setResizeWeight(0.55);
        splitPane.setContinuousLayout(true);

        JLabel countLabel = new JLabel(" Methods: " + methods.size());
        countLabel.setBorder(BorderFactory.createEmptyBorder(2, 2, 2, 2));
        add(countLabel, BorderLayout.NORTH);
        add(splitPane, BorderLayout.CENTER);

        if (!methods.isEmpty()) {
            table.setRowSelectionInterval(0, 0);
        }
    }

    private void showDetail(MethodInfo methodInfo) {
        flagsTable.setFlags(methodInfo.getAccessFlags().toInt());
        String text = TextCapture.safeCapture(wrapper ->
                new MethodInfoPresenter(result, wrapper, methodInfo).present());
        detailArea.setText(text);
        detailArea.setCaretPosition(0);
    }

    private static class MethodsTableModel extends AbstractTableModel {

        private static final String[] COLUMNS = {"access flags", "name", "descriptor", "attributes"};

        private final ConstantPool constantPool;
        private final List<MethodInfo> methods;

        private MethodsTableModel(ConstantPool constantPool, List<MethodInfo> methods) {
            this.constantPool = constantPool;
            this.methods = methods;
        }

        @Override
        public int getRowCount() {
            return methods.size();
        }

        @Override
        public int getColumnCount() {
            return COLUMNS.length;
        }

        @Override
        public String getColumnName(int column) {
            return COLUMNS[column];
        }

        @Override
        public Object getValueAt(int rowIndex, int columnIndex) {
            MethodInfo method = methods.get(rowIndex);
            return switch (columnIndex) {
                case 0 -> method.buildAccessFlagsLine().replaceAll("^flags: \\(0x[0-9a-f]+\\)\\s*", "");
                case 1 -> constantPool.desc(method.getNameIndex());
                case 2 -> constantPool.desc(method.getDescriptorIndex());
                case 3 -> method.getAttributes().getCount();
                default -> "";
            };
        }
    }
}
